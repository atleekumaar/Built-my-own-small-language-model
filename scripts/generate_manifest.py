def generate_manifest():
    manifest_entries = []
    for item in ARTIFACTS_METADATA:
        fpath = REPO_ROOT / item["path"]
        if not fpath.exists():
            print(f"Warning: File not found: {fpath}")
            continue

        raw_bytes = fpath.read_bytes()
        sha256 = hashlib.sha256(raw_bytes).hexdigest()
        size_bytes = len(raw_bytes)

        entry = dict(item)
        entry["size_bytes"] = size_bytes
        entry["size_human"] = f"{size_bytes / (1024 * 1024):.2f} MB" if size_bytes > 1024*1024 else f"{size_bytes / 1024:.2f} KB"
        entry["sha256"] = sha256
        manifest_entries.append(entry)

    manifest_data = {
        "schema_version": "1.0.0",
        "generated_timestamp_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "total_artifacts": len(manifest_entries),
        "artifacts": manifest_entries,
    }

    out_file = REPO_ROOT / "experiments" / "manifests" / "artifact_manifest.json"
    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(manifest_data, f, indent=2)

    print(f"Generated manifest with {len(manifest_entries)} artifacts at: {out_file}")


if __name__ == "__main__":
    generate_manifest()
